-- Sujet C · La composition des menus · schéma PostgreSQL (aussi compatible H2 pour les tests)

CREATE TABLE IF NOT EXISTS ingredient (
    nom          VARCHAR(120) PRIMARY KEY,
    unite_achat  VARCHAR(10)  NOT NULL,
    frais        BOOLEAN      NOT NULL,
    allergenes   VARCHAR(400)            -- NULL = « à compléter », '' = « aucun allergène » (RM18)
);

CREATE TABLE IF NOT EXISTS prix_ingredient (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_nom    VARCHAR(120)     NOT NULL REFERENCES ingredient (nom),
    valeur            DOUBLE PRECISION NOT NULL CHECK (valeur > 0),   -- RM13
    date_application  DATE             NOT NULL
);

CREATE TABLE IF NOT EXISTS recette (
    nom                VARCHAR(120)     PRIMARY KEY,
    type_recette       VARCHAR(20)      NOT NULL,
    quantite_produite  DOUBLE PRECISION NOT NULL,
    unite_produite     VARCHAR(10)      NOT NULL
);

CREATE TABLE IF NOT EXISTS composant (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recette_nom      VARCHAR(120)     NOT NULL REFERENCES recette (nom),
    ordre            INTEGER          NOT NULL,
    ingredient_nom   VARCHAR(120)     REFERENCES ingredient (nom),
    preparation_nom  VARCHAR(120)     REFERENCES recette (nom),
    quantite         DOUBLE PRECISION NOT NULL CHECK (quantite > 0),  -- RM8
    unite            VARCHAR(10)      NOT NULL
);

CREATE TABLE IF NOT EXISTS menu (
    nom   VARCHAR(120) PRIMARY KEY,
    etat  VARCHAR(20)  NOT NULL
);

CREATE TABLE IF NOT EXISTS menu_plat (
    menu_nom     VARCHAR(120) NOT NULL REFERENCES menu (nom),
    ordre        INTEGER      NOT NULL,
    recette_nom  VARCHAR(120) NOT NULL REFERENCES recette (nom),
    PRIMARY KEY (menu_nom, ordre)
);

CREATE TABLE IF NOT EXISTS prix_de_vente (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_nom       VARCHAR(120)     NOT NULL REFERENCES menu (nom),
    type_client    VARCHAR(20)      NOT NULL,
    couverts       INTEGER          NOT NULL CHECK (couverts > 0),    -- RM2
    prix           DOUBLE PRECISION NOT NULL,
    cout_revient   DOUBLE PRECISION NOT NULL,
    date_fixation  DATE             NOT NULL,
    CHECK (prix >= cout_revient)                                      -- RM5
);
